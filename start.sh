#!/bin/bash
# Запуск run.mjs с защитой от сна системы (важно для режима с закрытой
# крышкой на внешнем мониторе — без этого macOS уснёт и мониторинг матчей
# остановится до перезапуска процесса).
#
# caffeinate -s держит систему активной, пока этот процесс жив и ноутбук
# на питании (не помогает от разряда батареи — это осознанное ограничение,
# только сон по простою/крышке). Завершается сам, когда завершится node
# run.mjs (Ctrl+C или конец дня) — после этого обычное поведение сна
# возвращается без какой-либо ручной настройки.

cd "$(dirname "$0")"
caffeinate -is node run.mjs
